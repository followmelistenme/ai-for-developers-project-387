import { expect, test } from "./fixtures"

test("владелец создаёт черновик через настоящий API и видит его после перезагрузки", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.goto("/")
  await page.getByRole("link", { name: "Для владельца", exact: true }).click()
  await expect(page).toHaveURL(/\/owner$/)
  await expect(page.getByRole("heading", { name: "Пока нет типов встреч" })).toBeVisible()
  await page.getByRole("button", { name: "Создать тип встречи", exact: true }).click()
  await page.getByLabel("Название", { exact: true }).fill("  Знакомство с командой  ")
  await page.getByLabel("Описание", { exact: true }).fill("Обсудим <b>планы</b> и познакомимся.")
  await page.getByLabel("Длительность", { exact: true }).selectOption("45")
  await page.getByRole("button", { name: "Сохранить черновик", exact: true }).click()
  await expect(page.getByRole("status")).toHaveText("Черновик сохранён")
  await page.reload()
  const draft = page.getByRole("article", { name: "Знакомство с командой" })
  await expect(draft.getByText("Черновик", { exact: true })).toBeVisible()
  await expect(draft.getByText("45 минут", { exact: true })).toBeVisible()
  await expect(draft.getByText("Обсудим <b>планы</b> и познакомимся.", { exact: true })).toBeVisible()
  await expect(draft.getByRole("button", { name: "Опубликовать", exact: true })).toBeVisible()
  for (const width of [320, 390]) {
    await page.setViewportSize({ width, height: 844 })
    await expect(page.getByRole("heading", { name: "Типы встреч", exact: true })).toBeVisible()
    await expect.poll(() => page.locator("html").evaluate((element: { scrollWidth: number }) => element.scrollWidth)).toBeLessThanOrEqual(width)
    await page.getByRole("button", { name: "Создать тип встречи", exact: true }).click()
    await expect(page.getByRole("button", { name: "Сохранить черновик", exact: true })).toBeVisible()
    await expect.poll(() => page.locator("html").evaluate((element: { scrollWidth: number }) => element.scrollWidth)).toBeLessThanOrEqual(width)
    await page.getByRole("button", { name: "Отмена", exact: true }).click()
  }
  expect(errors).toEqual([])
})

test("ошибка API показана у названия, введённые данные можно исправить", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 844 })
  await page.goto("/owner")
  await page.getByRole("button", { name: "Создать тип встречи", exact: true }).click()
  await page.getByLabel("Название", { exact: true }).fill("   ")
  await page.getByLabel("Описание", { exact: true }).fill("Сохраним описание после ошибки")
  await page.getByLabel("Длительность", { exact: true }).selectOption("60")
  const rejected = page.waitForResponse((response) => response.url().endsWith("/api/owner/meeting-types") && response.request().method() === "POST")
  await page.getByRole("button", { name: "Сохранить черновик", exact: true }).click()
  expect((await rejected).status()).toBe(400)
  await expect(page.getByText("Введите название от 1 до 100 символов", { exact: true })).toBeVisible()
  await expect(page.getByLabel("Название", { exact: true })).toHaveAttribute("aria-invalid", "true")
  await expect(page.getByLabel("Описание", { exact: true })).toHaveValue("Сохраним описание после ошибки")
  await expect(page.getByLabel("Длительность", { exact: true })).toHaveValue("60")
  await page.getByLabel("Название", { exact: true }).fill("Исправленный черновик")
  await page.getByRole("button", { name: "Сохранить черновик", exact: true }).click()
  const draft = page.getByRole("article", { name: "Исправленный черновик" })
  await expect(draft.getByText("Сохраним описание после ошибки", { exact: true })).toBeVisible()
  await expect(draft.getByText("60 минут", { exact: true })).toBeVisible()
})
